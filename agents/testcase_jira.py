"""Reading a JIRA story: from the API or a local XML export, its Feature/Epic hierarchy, and its acceptance criteria.

Split out of agents/testcase_writer.py, which re-exports every name below, so
`agents.testcase_writer.<name>` keeps working. Code is moved verbatim.
"""

from __future__ import annotations

import re
from pathlib import Path

from agents.artifact_io import read_text_file
from agents.testcase_design_docs import _read_local_design_doc
from utils.run_layout import artifact_path


def fetch_jira_story_from_file(path: Path) -> dict:
    """Parses a local JIRA XML export (Tools > Export > XML Word format, or
    the ?view=rss single-issue export) instead of calling the live REST API.

    Added for orgs where the pipeline can't reach JIRA directly but a human
    can download the issue XML from the browser (confirmed against real
    exports from jira.example.com — the RSS/channel/item shape
    generated by JIRA Server/Data Center's XML view). Cloud instances may
    emit slightly different field names; the lookups below fall back to
    None/[] rather than raising if a field is missing.
    """
    import xml.etree.ElementTree as ET

    root = ET.parse(str(path)).getroot()
    item = root.find(".//item")
    if item is None:
        raise ValueError(f"'{path}' has no <item> element — not a JIRA XML export.")

    def text(tag, default=""):
        el = item.find(tag)
        return (el.text or default).strip() if el is not None and el.text else default

    key_el = item.find("key")
    story_key = key_el.text.strip() if key_el is not None and key_el.text else path.stem

    # <description> is HTML (JIRA wraps the wiki-rendered body in <p>/<ul>
    # tags) — strip tags for a clean text block rather than feeding raw HTML
    # to the LLM. re.sub is sufficient here (no nested scripts/styles to
    # worry about in a JIRA-rendered description).
    raw_description = text("description")
    description_text = re.sub(r"<[^>]+>", " ", raw_description)
    description_text = re.sub(r"&nbsp;|&#160;", " ", description_text)
    description_text = re.sub(r"[ \t]+", " ", description_text)
    description_text = re.sub(r"\n\s*\n+", "\n\n", description_text).strip()

    # Acceptance Criteria sometimes lives in a dedicated custom field
    # (customfieldname == "Acceptance Criteria", confirmed in real exports
    # like PROJ-68479.xml) rather than inside the description body — check
    # that first, same fallback-to-description-scan as the live-API path.
    acceptance_criteria = []
    for cf in item.findall(".//customfield"):
        name_el = cf.find("customfieldname")
        if name_el is not None and (name_el.text or "").strip() == "Acceptance Criteria":
            for val in cf.findall(".//customfieldvalue"):
                if val.text:
                    ac_text = re.sub(r"<[^>]+>", " ", val.text)
                    ac_text = re.sub(r"&nbsp;|&#160;", " ", ac_text).strip()
                    if ac_text:
                        acceptance_criteria.append(ac_text)
    if not acceptance_criteria:
        acceptance_criteria = _extract_acceptance_criteria(description_text)

    epic_key = ""
    for cf in item.findall(".//customfield"):
        name_el = cf.find("customfieldname")
        if name_el is not None and (name_el.text or "").strip() == "Epic Link":
            val = cf.find(".//customfieldvalue")
            if val is not None and val.text:
                epic_key = val.text.strip()

    return {
        "story_key": story_key,
        "epic_key": epic_key,
        "title": text("summary") or text("title"),
        "description": description_text,
        "acceptance_criteria": acceptance_criteria or ([description_text] if description_text else []),
        "status": text("status"),
        "issue_type": text("type"),
        "source": "local_xml_file",
    }


def fetch_jira_story(story_key: str, epic_key: str) -> dict:
    """Fetches real story + epic data from JIRA's REST API v3.

    Requires JIRA_BASE_URL, JIRA_API_TOKEN in your environment (see
    .env.example) — plus JIRA_EMAIL for basic auth. Falls back to
    placeholder data with a clear warning if credentials are missing, so
    the pipeline doesn't crash — it just tells you plainly it's running on
    fake data instead of silently doing so.

    Auth scheme: set JIRA_AUTH_TYPE=bearer (a Personal Access Token in the
    Authorization header) or JIRA_AUTH_TYPE=basic (email + API token via
    HTTP Basic). If unset, defaults to basic for *.atlassian.net (Cloud)
    and bearer for everything else — self-hosted Server/Data Center
    instances commonly issue PATs rather than accepting basic auth.
    """
    import os

    import requests
    from requests.auth import HTTPBasicAuth

    base_url = os.environ.get("JIRA_BASE_URL", "")
    email = os.environ.get("JIRA_EMAIL", "")
    token = os.environ.get("JIRA_API_TOKEN", "")
    # API v3 is JIRA Cloud only. Self-hosted Server/Data Center instances
    # (URLs that aren't *.atlassian.net) only support v2. Auto-detect, but
    # allow an explicit override via JIRA_API_VERSION if detection is wrong
    # for your instance.
    api_version = os.environ.get("JIRA_API_VERSION") or ("3" if "atlassian.net" in base_url else "2")
    auth_type = os.environ.get("JIRA_AUTH_TYPE", "").lower() or \
        ("basic" if "atlassian.net" in base_url else "bearer")

    if not base_url or not token or (auth_type == "basic" and not email):
        missing = "JIRA_BASE_URL/JIRA_API_TOKEN" + (" (+ JIRA_EMAIL for basic auth)" if auth_type == "basic" else "")
        print(f"⚠️  JIRA credentials missing ({missing}) "
              "— returning placeholder data. Set these in .env for real JIRA data.")
        return {
            "story_key": story_key,
            "epic_key": epic_key,
            "title": "[PLACEHOLDER] Fetch story title via JIRA MCP",
            "description": "[PLACEHOLDER] Fetch description via JIRA MCP",
            "acceptance_criteria": ["[PLACEHOLDER] Fetch AC via JIRA MCP"],
        }

    headers = {"Accept": "application/json"}
    auth = None
    if auth_type == "bearer":
        headers["Authorization"] = f"Bearer {token}"
    else:
        auth = HTTPBasicAuth(email, token)

    def _fetch_issue(key: str) -> dict:
        resp = requests.get(
            f"{base_url}/rest/api/{api_version}/issue/{key}",
            auth=auth, headers=headers, timeout=15,
        )
        resp.raise_for_status()
        return resp.json()

    # A STORY KEY JIRA DOES NOT HAVE IS NOT A CRASH.
    #
    # Missing credentials already degrade to placeholder data with a warning,
    # and the epic fetch below already tolerates an HTTP error — the story
    # fetch was the one path that raised, so a feature defined locally rather
    # than in JIRA (this project runs several, keyed "REG", "SANITY") killed
    # the whole stage with a bare `404 Client Error` and no indication that a
    # perfectly good reviewed sheet was sitting right there. The same
    # judgment the two neighbouring paths already make applies here.
    try:
        story_issue = _fetch_issue(story_key)
    except requests.HTTPError as exc:
        status = getattr(exc.response, "status_code", "?")
        print(f"⚠️  JIRA has no issue {story_key!r} (HTTP {status}) — continuing without "
              f"story context. Test cases will be written from the sheet, the ledger "
              f"and any --design-doc instead. Pass a real JIRA key, or a local XML "
              f"export via --story, if you want the story's own text used.")
        return {
            "story_key": story_key,
            "epic_key": epic_key,
            "title": f"{story_key} (not in JIRA)",
            "description": "",
            "acceptance_criteria": [],
            "jira_lookup_failed": True,
        }
    except requests.RequestException as exc:
        # A timeout/connection drop is transient, not "this issue doesn't
        # exist" — same degrade-don't-crash treatment as the HTTPError case
        # above, so one flaky request doesn't take down an entire multi-story
        # batch (see run()'s per-story ThreadPoolExecutor below, which this
        # loop feeds and which already assumes a story can fail alone).
        print(f"⚠️  JIRA request for {story_key!r} failed ({exc.__class__.__name__}) — "
              f"continuing without story context.")
        return {
            "story_key": story_key,
            "epic_key": epic_key,
            "title": f"{story_key} (JIRA unreachable)",
            "description": "",
            "acceptance_criteria": [],
            "jira_lookup_failed": True,
        }
    story_fields = story_issue.get("fields", {})

    # Description in JIRA v3 API is Atlassian Document Format (rich JSON), not
    # plain text. This does a simple text-node walk — good enough for feeding
    # to the LLM as context; it won't preserve tables/formatting, which is fine
    # for this use case (we just need the substance, not the layout).
    description_text = _extract_text_from_adf(story_fields.get("description"))

    # Acceptance criteria commonly lives in a custom field (varies per JIRA
    # instance) or inside the description itself. There's no universal field
    # ID across orgs, so we fall back to scanning the description for an
    # "Acceptance Criteria" section rather than guessing a custom field ID.
    acceptance_criteria = _extract_acceptance_criteria(description_text)

    epic_title = ""
    try:
        epic_issue = _fetch_issue(epic_key)
        epic_title = epic_issue.get("fields", {}).get("summary", "")
    except requests.RequestException:
        print(f"⚠️  Could not fetch epic {epic_key} — continuing with story data only.")

    return {
        "story_key": story_key,
        "epic_key": epic_key,
        "epic_title": epic_title,
        "title": story_fields.get("summary", ""),
        "description": description_text,
        # [""] would read as one empty criterion; no description means no AC.
        "acceptance_criteria": acceptance_criteria or ([description_text] if description_text else []),
        "status": story_fields.get("status", {}).get("name", ""),
        "issue_type": story_fields.get("issuetype", {}).get("name", ""),
    }


#: Attachment extensions worth feeding into generation through the same path
#: real knowledge-dir documents already use (see utils/app_design_doc.py and
#: the ingestion list in .env's TESTCASE_WRITER_KNOWLEDGE_DIR comment).
_INGESTIBLE_ATTACHMENT_EXTS = {
    ".docx", ".pdf", ".txt", ".md", ".csv", ".json", ".yaml", ".yml",
    ".png", ".jpg", ".jpeg", ".gif", ".webp",
}


#: Per-item ceilings on the hierarchy block sent with every story's prompt.
_MAX_DESCRIPTION_CHARS = 3000
_MAX_COMMENT_CHARS = 1000
_MAX_COMMENTS_PER_ISSUE = 10
_MAX_ATTACHMENT_CHARS = 4000
_MAX_ATTACHMENTS_PER_ISSUE = 5
_MAX_LINKED_TESTS = 20


def _clip(text: str, limit: int) -> str:
    text = text or ""
    return text if len(text) <= limit else text[:limit].rstrip() + " ...[truncated]"


def fetch_jira_hierarchy(entry_link: str, feature_dir: Path, story_key: str = "") -> dict:
    """Walks UP to the Feature/Epic and DOWN to linked Zephyr Test issues
    from one pasted Jira link/key (Feature, Epic, Story or Test — any
    level), collecting each issue's description, comments and attachments.

    This is additive, enrichment-only data merged into `jira_data` by the
    caller — a failure anywhere here (no credentials, an unreachable link, a
    deleted parent) degrades to an empty hierarchy block rather than
    breaking the single-story fetch `fetch_jira_story` already does.

    Returns {} if JIRA_FEATURE_LINK/--feature-link was not actually usable
    (no credentials, or the link had no recognizable issue key).
    """
    import os

    from utils import jira_client as _jc

    entry_key = _jc.extract_issue_key(entry_link)
    if not entry_key:
        print(f"⚠️  Could not find a JIRA issue key in {entry_link!r} — "
              "skipping hierarchy walk.")
        return {}

    client = _jc.JiraClient()
    if not client.configured:
        print("⚠️  JIRA credentials missing — skipping hierarchy walk for "
              f"{entry_key}. Set JIRA_BASE_URL/JIRA_API_TOKEN in .env.")
        return {}

    entry_issue = client.get_issue(entry_key)
    if not entry_issue:
        print(f"⚠️  JIRA has no issue {entry_key!r} reachable — skipping hierarchy walk.")
        return {}

    test_issue_type = os.environ.get("JIRA_TEST_ISSUE_TYPE", "Test")
    attachments_dir = artifact_path(feature_dir, "jira_attachments")

    all_images = []  # collected across every issue, returned once at the end

    def _summarize(issue: dict, role: str) -> dict:
        fields = issue.get("fields", {})
        key = issue.get("key", "")
        comments = [
            _extract_text_from_adf(c.get("body"))
            for c in client.get_comments(key) if c.get("body")
        ]
        attachment_texts = []
        for attachment in client.list_attachments(issue):
            name = attachment.get("filename", "")
            suffix = Path(name).suffix.lower()
            if suffix not in _INGESTIBLE_ATTACHMENT_EXTS:
                continue
            saved = client.download_attachment(attachment, attachments_dir)
            if not saved:
                continue
            if suffix in (".png", ".jpg", ".jpeg", ".gif", ".webp"):
                all_images.append(str(saved))
            elif suffix in (".docx", ".pdf"):
                # Reuses the same doc-to-sections reader the Figma/design-doc
                # path already relies on (`_read_local_design_doc`) — a Jira
                # attachment is read the same way a locally-supplied design
                # doc is, rather than inventing a second parser.
                doc = _read_local_design_doc(saved, feature_dir)
                sections = doc.get("sections") or doc.get("frames") or []
                text = "\n\n".join(
                    f"{s.get('heading', '')}\n{s.get('content', '')}" if isinstance(s, dict) else str(s)
                    for s in sections
                )
                if text.strip():
                    attachment_texts.append(f"[{name}]\n{text.strip()}")
                all_images.extend(p for p in doc.get("screenshots", []) if Path(p).is_file())
            else:
                text = read_text_file(saved)
                if text.strip():
                    attachment_texts.append(f"[{name}]\n{text.strip()}")
        # Capped: this block is re-sent with every story's prompt, and a long
        # comment thread or a pasted-in document would dominate it.
        kept_comments = [_clip(c, _MAX_COMMENT_CHARS) for c in comments if c.strip()]
        return {
            "role": role,
            "key": key,
            "issue_type": fields.get("issuetype", {}).get("name", ""),
            "title": fields.get("summary", ""),
            "description": _clip(_extract_text_from_adf(fields.get("description")),
                                 _MAX_DESCRIPTION_CHARS),
            "comments": kept_comments[:_MAX_COMMENTS_PER_ISSUE],
            "attachments": [_clip(a, _MAX_ATTACHMENT_CHARS)
                            for a in attachment_texts[:_MAX_ATTACHMENTS_PER_ISSUE]],
        }

    # Walk UP: entry issue, then its parent, then the parent's parent (Story
    # -> Epic -> Feature is at most two hops in this team's hierarchy; a
    # third hop is harmless if it exists, absent if it doesn't).
    chain = [entry_issue]
    current = entry_issue
    for _ in range(2):
        parent_key = client.parent_key(current)
        if not parent_key:
            break
        parent_issue = client.get_issue(parent_key)
        if not parent_issue:
            break
        chain.append(parent_issue)
        current = parent_issue

    # Name each level by its actual issue type rather than by chain position
    # — an entry link pasted at Story level has a 2-element chain (Story,
    # Epic), while one pasted at Epic level has (Epic, Feature); fixed
    # "feature"/"epic"/"story" keys would mislabel either case.
    # The entry issue is skipped when it IS the story being generated: its own
    # description and acceptance criteria are already in the prompt, so listing
    # it again as an "ancestor" only duplicates them.
    ancestors = [_summarize(issue, "ancestor") for issue in chain
                 if not (story_key and issue.get("key") == story_key)]

    # Walk DOWN: linked Test issues off the STORY specifically (or the entry
    # issue itself, if it already IS a Story or Test) — a Feature/Epic has no
    # direct Zephyr links, only its Stories do.
    story_issue = next(
        (i for i in chain if i.get("fields", {}).get("issuetype", {}).get("name") == "Story"),
        entry_issue,
    )
    linked_tests = [
        _summarize(t, "linked_test")
        for t in list(client.linked_issues_of_type(story_issue, test_issue_type))[:_MAX_LINKED_TESTS]
    ]

    if all_images:
        print(f"      JIRA hierarchy: {len(ancestors)} ancestor issue(s), "
              f"{len(linked_tests)} linked {test_issue_type} issue(s), "
              f"{len(all_images)} image(s) downloaded to {attachments_dir}.")
    else:
        print(f"      JIRA hierarchy: {len(ancestors)} ancestor issue(s), "
              f"{len(linked_tests)} linked {test_issue_type} issue(s).")

    return {
        "entry_key": entry_key, "ancestors": ancestors, "linked_test_cases": linked_tests,
        "screenshots": all_images,
    }


#: ADF node types that end a line of text.
_ADF_BLOCK_NODES = frozenset({"paragraph", "listItem", "heading", "tableRow", "codeBlock"})


def _extract_text_from_adf(adf_node) -> str:
    """Walks Atlassian Document Format JSON and pulls out plain text.
    ADF is a nested tree of {type, content, text} nodes."""
    if not adf_node:
        return ""
    if isinstance(adf_node, str):
        return adf_node

    # Inline text nodes (bold/italic/link runs inside ONE sentence) are joined
    # with "" — joining every text node with a newline split a formatted
    # sentence into fragments that _extract_acceptance_criteria then counted as
    # separate criteria. A newline is emitted only where a BLOCK ends.
    parts = []

    def walk(node):
        if isinstance(node, dict):
            node_type = node.get("type")
            if node_type == "text":
                parts.append(node.get("text", ""))
            elif node_type == "hardBreak":
                parts.append("\n")
            for child in node.get("content", []) or []:
                walk(child)
            if node_type in _ADF_BLOCK_NODES:
                parts.append("\n")
        elif isinstance(node, list):
            for item in node:
                walk(item)
    walk(adf_node)
    lines = [line.rstrip() for line in "".join(parts).split("\n")]
    return "\n".join(line for line in lines if line.strip())


#: Section names that legitimately END an Acceptance Criteria block. Used
#: instead of "any short line ending in a colon", which false-positived on
#: ordinary AC content like "Scenario 1:" or "Given user is logged in:" and
#: silently truncated the list.
_AC_SIBLING_SECTIONS = (
    "notes", "note", "background", "context", "out of scope", "scope",
    "dependencies", "design", "designs", "assumptions", "open questions",
    "questions", "technical notes", "implementation notes", "attachments",
    "definition of done", "test notes", "references",
)


#: Matches an Acceptance Criteria heading in the forms JIRA actually produces:
#: plain text, JIRA Server wiki markup ("h3. Acceptance Criteria"), and
#: bold/underscored variants ("*Acceptance Criteria:*"). The original exact
#: string match never fired on this instance's wiki-markup descriptions.
_AC_HEADING_RE = re.compile(
    r"^\s*(?:h[1-6]\.)?\s*[*_#\s]*acceptance\s*criteria\b[*_:\s]*$", re.I)


def _extract_acceptance_criteria(description_text: str) -> list:
    """Looks for an 'Acceptance Criteria' heading in the description text and
    pulls out the lines under it. Returns [] if no such section is found —
    caller falls back to using the full description in that case.

    Warns on both failure modes, because a silently empty or silently
    half-captured AC list means the Test Case Writer generates coverage for
    criteria it never saw, and nothing downstream can tell.
    """
    if not description_text:
        return []

    lines = description_text.split("\n")
    ac_lines = []
    capturing = False
    stopped_early = False
    for line in lines:
        stripped = line.strip()
        if _AC_HEADING_RE.match(stripped):
            capturing = True
            continue
        if capturing:
            if not stripped:
                continue
            # Stop only at a recognized SIBLING section heading — not at any
            # short colon-terminated line, which is normal AC phrasing.
            bare = stripped.lower().strip("*_#: ").strip()
            if bare in _AC_SIBLING_SECTIONS or (
                    stripped.lower().startswith("h") and len(stripped) > 3
                    and stripped[1].isdigit() and stripped[2] == "."
                    and stripped[3:].strip("*_: ").lower() in _AC_SIBLING_SECTIONS):
                stopped_early = True
                break
            ac_lines.append(stripped)

    if not capturing:
        print("⚠️  No 'Acceptance Criteria' heading found in the JIRA description — "
              "the Test Case Writer will fall back to the full description text.")
    elif not ac_lines:
        print("⚠️  Found an 'Acceptance Criteria' heading but no content under it — "
              "falling back to the full description text.")
    elif stopped_early:
        print(f"ℹ️  Captured {len(ac_lines)} acceptance criteria line(s); stopped at "
              f"the next section heading.")
    return ac_lines
