"""The framework scaffold, as data.

Held as a dict of path -> content rather than as a tree of real files on disk
for one reason that matters: a scaffold that can be PARTIALLY missing is
worse than no scaffold at all. If `BasePage.ts` fails to copy, every
generated page object imports something that does not exist, every file
compiles-checks red, and the repair loop burns its whole budget trying to fix
code that was never the problem. As a Python module it is either importable
or the package is broken — there is no half state.

The generated workspace IS a normal repository once written. A team edits
`workspaces/<app>/` by hand, commits it, and owns it. This module is only the
seed.

WHY A FIXED SCAFFOLD AT ALL. Two reasons, and the second is the one people
underestimate:

  1. A human has to own this suite after the agents stop running. Identical
     structure on every project is what makes that possible.
  2. It shrinks the model's output space. A Coding Agent that must invent a
     folder layout, a base class and a fixture convention on every run
     produces a different answer every run. One that fills slots in a known
     skeleton produces code that is far more reliably correct — and, because
     the imports are fixed and known, code the compile gate can actually
     check.

`fixtures/index.ts` carries the `captureFailureDom` fixture deliberately.
`run_pipeline` notes that without it, self-healing has no failure-time DOM to
work from and "healing will re-inspect live" — a far less reliable path.
Shipping it in the scaffold means every project this pipeline stands up gets
the good path by default instead of by remembering.
"""

