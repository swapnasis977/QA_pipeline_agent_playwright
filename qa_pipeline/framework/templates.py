AUTH_SETUP = """\
import { test as setup, expect } from '@playwright/test';
import fs from 'fs';
import { ENV } from '../src/config/env';
import { AUTH_STATE } from '../src/config/paths';

/**
 * Signs in ONCE per run and saves the session to AUTH_STATE, which every
 * other project loads via `storageState`. Generated by qa-pipeline's
 * framework scaffolder; safe to edit by hand.
 *
 * Why this exists: without it a scaffolded suite had no authentication at
 * all. Every generated UI spec opened the app, was redirected to the identity
 * provider, and failed on its first assertion — identically, every time, on
 * every project. The Reviewer diagnosed it correctly and the Self-Healer
 * correctly declined to patch it, because the gap is upstream of any spec:
 * you cannot fix a missing login by editing a locator.
 *
 * Both real-world shapes are handled, in one ordered flow rather than a
 * branch on "is a password box visible", because that test does not
 * discriminate: Entra ID PRE-RENDERS its password input on the email screen.
 * The presence of a dedicated ADVANCE control is what actually tells the two
 * apart. This mirrors utils/dom_inspector.py's `_attempt_login`, which learned
 * the same lesson against a real tenant.
 *
 *   - single-step: username + password together, one submit
 *   - two-step:    email -> Next -> password -> Sign in   (Entra ID, Okta)
 */

const USERNAME_FIELDS = [
  'input[type="email"]',
  'input[name="loginfmt"]',
  'input[name="username"]',
  'input[id="username"]',
  'input[name="email"]',
  'input[type="text"]',
];

const PASSWORD_FIELD = 'input[type="password"]';

setup('authenticate', async ({ page }) => {
  setup.skip(!ENV.user || !ENV.password,
    'APP_TEST_USER / APP_TEST_PASSWORD are not set - cannot sign in.');

  await page.goto(ENV.baseUrl, { waitUntil: 'domcontentloaded' });

  // The identity provider redirect can take a moment to settle. Wait for a
  // username box rather than a fixed timeout.
  const username = page.locator(USERNAME_FIELDS.join(', ')).first();
  const alreadySignedIn = await username
    .waitFor({ state: 'visible', timeout: 15_000 })
    .then(() => false)
    .catch(() => true);

  if (!alreadySignedIn) {
    await username.fill(ENV.user);

    // A dedicated advance control means a two-step IDP. Its absence means the
    // password box on this same screen is the live one.
    // waitFor, NOT isVisible. `locator.isVisible()` resolves IMMEDIATELY
    // against the current DOM: it accepts a `timeout` option but does not
    // wait for one. Every "optional control" probe in this file therefore
    // answered "no" the instant the previous click started a navigation,
    // whether or not the control was about to appear. See the KMSI block
    // below, where that silently skipped the step and failed the run.
    const advance = page.getByRole('button', { name: /^(next|continue)$/i }).first();
    const hasAdvance = await advance
      .waitFor({ state: 'visible', timeout: 3_000 })
      .then(() => true)
      .catch(() => false);
    if (hasAdvance) {
      await advance.click();
    }

    const password = page.locator(PASSWORD_FIELD).first();
    await password.waitFor({ state: 'visible', timeout: 15_000 });
    await password.fill(ENV.password);

    await page
      .getByRole('button', { name: /^(sign in|log in|login|submit|continue|next)$/i })
      .first()
      .click();
  }

  // "Stay signed in?" (KMSI). Answered NO so an automation run leaves no
  // long-lived token on the runner.
  //
  // Matched THREE ways because the control's markup is not stable across
  // tenants or across Entra's UI revisions. The id-and-input form below was
  // the only one matched originally, and on a current tenant it matches
  // nothing: the buttons now render as <button>, so `input[value="No"]`
  // cannot hit them and `#idBtn_Back` may be absent entirely. The sign-in had
  // SUCCEEDED, the run then sat on the interstitial until the assertion below
  // failed with "still on login.microsoftonline.com" — which reads as a
  // credential or MFA problem and is not one. Role+name is what actually
  // survives the re-skin; the id and input forms stay as the fallbacks that
  // work where the label is localized.
  const kmsi = page
    .locator('#idBtn_Back, input[value="No" i], button[value="No" i]')
    .or(page.getByRole('button', { name: /^[ ]*no[ ]*$/i }))
    .first();
  //
  // AND WAITED FOR, not probed. This is where `isVisible()`'s no-wait
  // behaviour actually bit: the check ran the moment the sign-in click
  // returned, before Entra had rendered the interstitial, so it answered
  // "not visible" every time and the click never happened. The run then sat
  // on "Stay signed in?" until the URL assertion below failed with "still on
  // login.microsoftonline.com" — which reads as bad credentials or MFA, and
  // was neither: the id this looked for was present and correct all along.
  const appeared = await kmsi
    .waitFor({ state: 'visible', timeout: 15_000 })
    .then(() => true)
    .catch(() => false);
  if (appeared) {
    await kmsi.click();
    // The click navigates. Without waiting, the URL assertion below can read
    // the interstitial's own URL and report a sign-in that in fact completed.
    await page.waitForLoadState('domcontentloaded').catch(() => undefined);
  }

  // No password box left anywhere in the flow. NECESSARY, NOT SUFFICIENT —
  // it is equally true on a consent screen, an error page, a KMSI
  // interstitial or a blank redirect, which is how a sign-in that never
  // reached the app once reported PASS while every test behind it failed at
  // step 1 with "element(s) not found" on a dashboard locator.
  await expect(page.locator(PASSWORD_FIELD)).toHaveCount(0, { timeout: 30_000 });
  await page.waitForLoadState('networkidle').catch(() => undefined);

  // WHERE DID WE ACTUALLY LAND? Still sitting on the identity provider means
  // the sign-in did not complete, however clean the screen looks.
  const landedOn = page.url();
  expect(landedOn, `Sign-in did not return to the application - the browser is still on ` +
    `${landedOn}. Check the screenshot before assuming bad credentials: if it shows a ` +
    `prompt rather than a password box ("Stay signed in?", consent, "Action required"), ` +
    `authentication SUCCEEDED and an interstitial this setup does not dismiss is what ` +
    `stopped it. Otherwise check APP_TEST_USER / APP_TEST_PASSWORD, and whether this ` +
    `tenant now requires MFA or admin consent (neither can be automated here).`)
    .not.toContain('login.microsoftonline.com');

  const appOrigin = new URL(ENV.baseUrl).origin;
  expect(landedOn, `Sign-in ended on ${landedOn}, which is not the application ` +
    `(${appOrigin}).`).toContain(appOrigin);

  await page.context().storageState({ path: AUTH_STATE });

  // IS THE SAVED SESSION ACTUALLY USABLE? `storageState` records cookies AND
  // per-origin local/session storage. An app that keeps its token in web
  // storage - most SPAs behind Azure AD - restores nothing from a state whose
  // `origins` array is empty, and every spec then starts logged out.
  // Observed exactly that way: 18 cookies, almost all belonging to
  // login.microsoftonline.com, and origins: 0.
  const saved = JSON.parse(fs.readFileSync(AUTH_STATE, 'utf-8'));
  const appCookies = (saved.cookies ?? []).filter((c: { domain: string }) =>
    appOrigin.includes(c.domain.replace(/^[.]/, '')));
  const appOrigins = (saved.origins ?? []).filter((o: { origin: string }) =>
    o.origin === appOrigin);

  if (appCookies.length === 0 && appOrigins.length === 0) {
    throw new Error(
      `Signed in, but the saved session carries nothing for ${appOrigin}: ` +
      `${(saved.cookies ?? []).length} cookie(s), none for the app, and ` +
      `origins: ${(saved.origins ?? []).length}. Every spec will start logged ` +
      `out and fail on its first locator. If this app keeps its token in ` +
      `sessionStorage, storageState cannot carry it between projects - sign in ` +
      `per worker instead, or seed the storage state explicitly.`);
  }
});
"""

