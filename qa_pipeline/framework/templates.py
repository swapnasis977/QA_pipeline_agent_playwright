BASE_PAGE = """\
import { Page, Locator, expect } from '@playwright/test';

/**
 * Every page object extends this.
 *
 * Two kinds of thing live here, and nothing else:
 *   1. the page lifecycle (`path`, `ready`, `goto`, `waitUntilReady`);
 *   2. INTERACTIONS THAT ARE EASY TO GET WRONG, so they are written once,
 *      correctly, instead of being re-derived per spec.
 *
 * The second group is not convenience. Each helper below exists because its
 * hand-rolled equivalent shipped, passed every gate, and failed against the
 * real application — the comments name which failure. Encoding them here is
 * what makes the difference between a scaffold you maintain in one place and
 * one whose defects you fix N times, once per spec.
 *
 * Still deliberately small: a fat base class is where behaviour hides, and a
 * page's own behaviour belongs on that page. Anything specific to ONE screen
 * goes in that screen's page object, not here.
 *
 * Note there are no explicit sleeps and none should be added. Playwright's
 * locators auto-wait; a `waitForTimeout` is the single most common cause of a
 * suite that is both slow and flaky.
 */
export abstract class BasePage {
  constructor(protected readonly page: Page) {}

  /** Route fragment this page lives at, for `goto()` and assertions. */
  abstract readonly path: string;

  /** A locator that is present if and only if this page has loaded. */
  abstract readonly ready: Locator;

  async goto(): Promise<void> {
    await this.page.goto(this.path);
    await this.waitUntilReady();
  }

  async waitUntilReady(): Promise<void> {
    await expect(this.ready).toBeVisible();
  }

  /**
   * Has this page loaded, waiting up to `timeout` for it?
   *
   * NOT `this.ready.isVisible()`. `locator.isVisible()` accepts a `timeout`
   * option but does NOT wait for one — it resolves immediately against the
   * current DOM. Called right after a click that starts a navigation it
   * answers "no" every time, whatever is about to render.
   *
   * That exact bug shipped in this scaffold's own `auth.setup.ts`: the
   * "Stay signed in?" prompt was probed with `isVisible()` before the page
   * had rendered, so it was never dismissed and EVERY test run failed at
   * sign-in — reported as a credentials/MFA problem, which it was not.
   */
  async isDisplayed(timeout = 10_000): Promise<boolean> {
    return this.appeared(this.ready, timeout);
  }

  /**
   * Did `locator` show up within `timeout`? The correct way to probe for
   * something OPTIONAL — a confirmation dialog that only appears when a
   * previous run left state behind, a cookie banner, an interstitial.
   *
   * Use this anywhere the honest answer is "maybe". Never `isVisible()`
   * (see `isDisplayed`), and never a bare `waitFor` without the `.catch`,
   * which turns "it wasn't there" into a test failure.
   */
  protected async appeared(locator: Locator, timeout = 5_000): Promise<boolean> {
    return locator
      .waitFor({ state: 'visible', timeout })
      .then(() => true)
      .catch(() => false);
  }

  /**
   * Fill a text input AND commit it.
   *
   * `.fill()` sets the value and dispatches `input`. It does NOT dispatch
   * `change` — natively, `change` fires only when the field loses focus. An
   * application that commits typed values to its own model on `change`
   * therefore keeps an EMPTY model while the DOM shows everything the test
   * typed, and its submit step then rejects the form with required/mandatory
   * errors on fields that are visibly populated.
   *
   * That failure cost this project several full runs and both Self-Healer
   * attempts before it was understood, because nothing about the symptom
   * points at the cause. Prefer this over a bare `.fill()` on any field whose
   * value the application later reads back.
   */
  protected async fillAndCommit(locator: Locator, value: string): Promise<void> {
    await locator.fill(value);
    await locator.blur();
  }

  /**
   * Type a value key by key, then commit it.
   *
   * For fields whose validation only reacts to REAL key events: character
   * counters, "the Save button enables once you type something", inputs
   * wired to `keyup`. `.fill()` sets such a field's value and the app never
   * notices, so the control it gates stays disabled forever.
   */
  protected async typeAndCommit(locator: Locator, value: string): Promise<void> {
    await locator.click();
    await locator.pressSequentially(value);
    await locator.blur();
  }

  /**
   * Assert a form field holds `value`.
   *
   * An input's value is NOT a text node, so `getByText(value)` and
   * `toBeVisible()` can never match it however long they wait. A spec that
   * asserted `getByText('01/01/1990')` against a populated Date of Birth
   * input timed out with the value on screen the whole time — and was then
   * "healed" twice by widening the timeout.
   */
  protected async expectFieldValue(locator: Locator, value: string | RegExp): Promise<void> {
    await expect(locator).toHaveValue(value);
  }

  /**
   * Click a control that is disabled via a CSS CLASS rather than the native
   * `disabled` attribute (`class="btn btn-primary disabled"`).
   *
   * `toBeEnabled()` passes on such an element — there is no `disabled`
   * attribute to fail on — while the application's own handler still refuses
   * the click, so the step runs, throws nothing, and does nothing. Waiting
   * for the class to clear is what actually gates it.
   */
  protected async clickWhenEnabled(locator: Locator, timeout = 15_000): Promise<void> {
    await expect(locator).toBeVisible({ timeout });
    await expect(locator).not.toHaveClass(/\bdisabled\b/, { timeout });
    await locator.click();
  }

  get title(): Promise<string> {
    return this.page.title();
  }
}
"""

BASE_COMPONENT = """\
import { Locator, Page } from '@playwright/test';

/**
 * A Component Object: a reusable control that appears on many pages — a data
 * grid, a date picker, a modal, a nav bar.
 *
 * Every component is scoped to a root Locator rather than to the Page. That
 * scoping is what makes a component safe to use twice on one screen, and it
 * is the main structural defence against the ambiguous-locator failure where
 * a name matches both a sidebar item and a dashboard tile: inside a scoped
 * root, it can only match one.
 */
export abstract class BaseComponent {
  protected readonly page: Page;

  constructor(protected readonly root: Locator) {
    this.page = root.page();
  }

  /**
   * Is this component on screen, waiting up to `timeout` for it?
   *
   * NOT `this.root.isVisible()`. `locator.isVisible()` takes a `timeout`
   * option but does not wait for one — it answers from the CURRENT DOM and
   * returns immediately, so a component that is one render away reports
   * absent. The same defect in this scaffold's `auth.setup.ts` meant an
   * interstitial was never dismissed and every run failed at sign-in.
   */
  async isVisible(timeout = 5_000): Promise<boolean> {
    return this.root
      .waitFor({ state: 'visible', timeout })
      .then(() => true)
      .catch(() => false);
  }

  protected byRole(role: Parameters<Locator['getByRole']>[0], name: string | RegExp): Locator {
    return this.root.getByRole(role, { name });
  }

  protected byTestId(testId: string): Locator {
    return this.root.getByTestId(testId);
  }
}
"""

