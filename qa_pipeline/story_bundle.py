"""`qa-pipeline bundle`: one folder per story holding everything a person needs.

The test cases live under `runs/<app>/<epic>_<story>/` but the scripts live in the shared framework
repo (`workspaces/<app>/tests/`), so reading one story meant opening both trees. This copies the
story's spec files next to its test cases and writes a README that says what is there and how to run it:

    runs/<app>/<epic>_<story>/
      README.md               start here: counts, the spec list, how to run
      summary.md
      1_testcases/            the sheets
      2_automation/scripts/   COPIES of this story's specs (the framework stays in workspaces/<app>/)
      3_results/

The copies are regenerated on every call and are for reading; edit the spec in the workspace, which
is the one that runs. The framework (src/, config, package.json) is never duplicated.

A spec belongs to a story when the run's generated_files.json lists it; a run with no manifest falls back
to test titles carrying `<epic>-AUTO-` or `<story>-AUTO-`. Deterministic: no model, no network.
"""

from __future__ import annotations

import json
import re
import shutil
from pathlib import Path

from utils.run_layout import artifact_path

_FOLDER = re.compile(r"^(?P<epic>[A-Z][A-Z0-9]*-\d+|DOC)_(?P<story>.+)$")
_CASE_ID = re.compile(r"[A-Z][A-Z0-9]*-\d+-AUTO-TC-\d+")


def story_keys(folder_name: str) -> list[str]:
    """The Jira-style keys a run folder name carries: `PROJ-68294_PROJ-68309` -> both; `X_FEATURE` -> epic only."""
    m = _FOLDER.match(folder_name)
    if not m:
        return []
    keys = [m["epic"]]
    if re.fullmatch(r"[A-Z][A-Z0-9]*-\d+", m["story"]):
        keys.append(m["story"])
    return keys


def _listed(run_dir: Path) -> set[str]:
    """Paths the Coding Agent recorded for this run, if it left a manifest."""
    manifest = artifact_path(run_dir, "generated_files.json")
    if not manifest.is_file():
        return set()
    try:
        rows = json.loads(manifest.read_text(encoding="utf-8"))
    except ValueError:
        return set()
    return {str(r.get("path", "")).replace("\\", "/") for r in rows if isinstance(r, dict)}


def specs_for(run_dir: Path, workspace: Path) -> dict[Path, list[str]]:
    """{spec path in the workspace: the case ids of this story inside it}.

    The run's own manifest is exact: it lists the specs THIS run wrote, so two stories of one epic
    cannot take each other's scripts. Only a run with no manifest (an older one) falls back to
    matching `<epic>-AUTO-` / `<story>-AUTO-` in the test titles.
    """
    keys = story_keys(run_dir.name)
    listed = {p for p in _listed(run_dir) if p.endswith(".spec.ts")}
    found: dict[Path, list[str]] = {}
    for spec in sorted((workspace / "tests").rglob("*.spec.ts")):
        rel = spec.relative_to(workspace).as_posix()
        text = spec.read_text(encoding="utf-8", errors="replace")
        ids = sorted({i for i in _CASE_ID.findall(text) if any(i.startswith(f"{k}-AUTO-") for k in keys)})
        if listed:
            if rel in listed:
                found[spec] = ids
        elif ids:
            found[spec] = ids
    return found


def shared_with(run_dir: Path, workspace: Path, spec: Path) -> list[str]:
    """Other runs whose manifest also lists this spec (it holds cases of more than one story)."""
    rel = spec.relative_to(workspace).as_posix()
    return [d.name for d in sorted(run_dir.parent.iterdir())
            if d.is_dir() and d != run_dir and not d.name.startswith("_") and rel in _listed(d)]


def _readme(run_dir: Path, profile_name: str, workspace: Path, specs: dict[Path, list[str]]) -> str:
    total = sum(len(v) for v in specs.values())
    def _shared(p: Path) -> str:
        others = shared_with(run_dir, workspace, p)
        return f"also written by {', '.join(others)}" if others else ""

    rows = "\n".join(
        f"| `{p.relative_to(workspace / 'tests').as_posix()}` | {len(ids)} | {_shared(p)} |"
        for p, ids in specs.items()
    )
    # Case ids carry the epic prefix, so that is what --grep can match.
    grep = f"{(story_keys(run_dir.name) or [run_dir.name])[0]}-AUTO"
    return f"""# {run_dir.name}

Everything for this story in one place. Generated by `bundle`; safe to regenerate.

| What | Where |
|---|---|
| Summary of the run | `summary.md` |
| Test cases (sheets) | `1_testcases/` |
| Automation scripts (copies, read-only) | `2_automation/scripts/` |
| Results, bugs, evidence | `3_results/` |
| The framework that runs them | `{workspace}` (shared by every story; not copied here) |

## Scripts: {len(specs)} files, {total} automated cases

| Spec | Cases | Shared |
|---|---|---|
{rows}

## Run them

The scripts here are copies. They run from the framework, so edit the spec in
`{workspace / 'tests'}` and re-run `bundle` to refresh these copies.

```bash
py -m qa_pipeline.cli execute --profile "{profile_name}" --grep {grep}
```
"""


def _write_reports(run_dir: Path, workspace: Path, specs: dict[Path, list[str]]) -> list[str]:
    """TRACEABILITY.md, EFFORT_REPORT.md and testdata_template.json; each is skipped when it has nothing to say."""
    from utils import effort_report, testdata_template, traceability

    written: list[str] = []
    matrix = traceability.build(run_dir, workspace)
    if matrix["rows"]:
        artifact_path(run_dir, "TRACEABILITY.md").write_text(
            traceability.render(run_dir.name, matrix), encoding="utf-8")
        written.append("TRACEABILITY.md")
    effort = effort_report.render(run_dir.name, effort_report.measure(run_dir, list(specs), matrix["totals"]))
    if effort:
        artifact_path(run_dir, "EFFORT_REPORT.md").write_text(effort, encoding="utf-8")
        written.append("EFFORT_REPORT.md")
    model_path = artifact_path(run_dir, "screen_model.json")
    model = json.loads(model_path.read_text(encoding="utf-8")) if model_path.is_file() else None
    template = testdata_template.build(traceability.load_cases(run_dir), model)
    if template:
        artifact_path(run_dir, "testdata_template.json").write_text(
            json.dumps(template, indent=2, ensure_ascii=False), encoding="utf-8")
        written.append("testdata_template.json")
    return written


def bundle_run(run_dir: Path, workspace: Path, profile_name: str) -> int | None:
    """Rebuild `2_automation/scripts/`, README.md and the reports for one run folder.

    None when there was nothing to write at all (no script belongs to it and no case sheet to report on).
    """
    specs = specs_for(run_dir, workspace)
    reports = _write_reports(run_dir, workspace, specs)
    if not specs:
        return 0 if reports else None
    target = artifact_path(run_dir, "scripts")
    if target.exists():
        shutil.rmtree(target)
    for spec in specs:
        dest = target / spec.relative_to(workspace / "tests")
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(spec, dest)
    artifact_path(run_dir, "README.md").write_text(
        _readme(run_dir, profile_name, workspace, specs), encoding="utf-8")
    return len(specs)


def cmd_bundle(args, profile) -> int:
    root = profile.context_root
    if not root.is_dir():
        print(f"      No runs under {root}.")
        return 1
    folders = [root / args.run] if args.run else sorted(
        d for d in root.iterdir() if d.is_dir() and not d.name.startswith("_"))
    done = 0
    for run_dir in folders:
        count = bundle_run(run_dir, profile.workspace, profile.name)
        if count is None:
            print(f"      {run_dir.name}: nothing to bundle (no script and no case sheet), skipped.")
            continue
        done += 1
        print(f"      {run_dir.name}: {count} spec(s) copied to 2_automation/scripts/; "
              f"TRACEABILITY.md / EFFORT_REPORT.md / testdata_template.json written where there was data.")
    return 0 if done else 1


def refresh_bundles(profile) -> None:
    """Rebuild every story folder's copies after a run or an execute. Never raises: a convenience, not a gate."""
    try:
        root = profile.context_root
        for run_dir in sorted(d for d in root.iterdir() if d.is_dir() and not d.name.startswith("_")):
            bundle_run(run_dir, profile.workspace, profile.name)
    except Exception as exc:  # noqa: BLE001
        print(f"      (story folders not refreshed: {exc})")
